import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const d = 'd' + 'i' + 'v';
const open = (cls) => `<${d}${cls ? ` className="${cls}"` : ''}>`;
const close = `</${d}>`;

const lines = [
  `import React, { useEffect, useState } from 'react';`,
  `import { useNavigate, useSearchParams, Link } from 'react-router-dom';`,
  `import { api, setToken } from '@/api/client';`,
  `import { Button } from '@/components/ui/button';`,
  `import { Input } from '@/components/ui/input';`,
  `import { Label } from '@/components/ui/label';`,
  `import { Building2, Loader2 } from 'lucide-react';`,
  ``,
  `const ROLE_LABELS = {`,
  `  admin: 'Administrator',`,
  `  user: 'Korisnik',`,
  `  viewer: 'Pregledač (samo čitanje)',`,
  `};`,
  ``,
  `export default function AcceptInvite() {`,
  `  const [searchParams] = useSearchParams();`,
  `  const token = searchParams.get('token') || '';`,
  `  const navigate = useNavigate();`,
  `  const [preview, setPreview] = useState(null);`,
  `  const [loadError, setLoadError] = useState('');`,
  `  const [loading, setLoading] = useState(true);`,
  `  const [submitting, setSubmitting] = useState(false);`,
  `  const [error, setError] = useState('');`,
  `  const [password, setPassword] = useState('');`,
  `  const [password2, setPassword2] = useState('');`,
  `  const [firstName, setFirstName] = useState('');`,
  `  const [lastName, setLastName] = useState('');`,
  ``,
  `  useEffect(() => {`,
  `    if (!token) {`,
  `      setLoadError('Nedostaje link pozivnice.');`,
  `      setLoading(false);`,
  `      return;`,
  `    }`,
  `    api.invites`,
  `      .preview(token)`,
  `      .then(setPreview)`,
  `      .catch((e) => setLoadError(e.message || 'Pozivnica nije važeća'))`,
  `      .finally(() => setLoading(false));`,
  `  }, [token]);`,
  ``,
  `  const handleSubmit = async (e) => {`,
  `    e.preventDefault();`,
  `    setError('');`,
  `    if (password.length < 6) {`,
  `      setError('Lozinka mora imati najmanje 6 karaktera.');`,
  `      return;`,
  `    }`,
  `    if (password !== password2) {`,
  `      setError('Lozinke se ne poklapaju.');`,
  `      return;`,
  `    }`,
  `    setSubmitting(true);`,
  `    try {`,
  `      const result = await api.invites.accept(token, {`,
  `        password,`,
  `        first_name: firstName,`,
  `        last_name: lastName,`,
  `      });`,
  `      if (result?.token) setToken(result.token);`,
  `      navigate('/', { replace: true });`,
  `      window.location.reload();`,
  `    } catch (err) {`,
  `      setError(err.message || 'Registracija nije uspela');`,
  `    }`,
  `    setSubmitting(false);`,
  `  };`,
  ``,
  `  return (`,
  `    ${open('min-h-screen bg-gradient-to-br from-slate-50 via-white to-blue-50 flex items-center justify-center p-6')}`,
  `      ${open('w-full max-w-md bg-white rounded-2xl shadow-xl border border-slate-200 p-8')}`,
  `        ${open('flex flex-col items-center mb-6')}`,
  `          ${open('w-14 h-14 rounded-2xl bg-gradient-to-br from-blue-600 to-blue-800 flex items-center justify-center mb-3')}`,
  `            <Building2 className="w-7 h-7 text-white" />`,
  `          ${close}`,
  `          <h1 className="text-2xl font-bold text-slate-800">Home Sorter</h1>`,
  `          <p className="text-slate-500 text-sm mt-1">Prihvatanje pozivnice</p>`,
  `        ${close}`,
  `        {loading && (`,
  `          ${open('flex justify-center py-8')}`,
  `            <Loader2 className="w-8 h-8 animate-spin text-slate-400" />`,
  `          ${close}`,
  `        )}`,
  `        {!loading && loadError && (`,
  `          ${open('text-center space-y-4')}`,
  `            <p className="text-red-600">{loadError}</p>`,
  `            <Link to="/login" className="text-blue-600 hover:underline text-sm">`,
  `              Idi na prijavu`,
  `            </Link>`,
  `          ${close}`,
  `        )}`,
  `        {!loading && preview && (`,
  `          <form onSubmit={handleSubmit} className="space-y-4">`,
  `            ${open('rounded-lg bg-slate-50 p-3 text-sm text-slate-600 space-y-1')}`,
  `              <p><span className="font-medium text-slate-800">Email:</span> {preview.email}</p>`,
  `              <p><span className="font-medium text-slate-800">Uloga:</span> {ROLE_LABELS[preview.role] || preview.role}</p>`,
  `            ${close}`,
  `            ${open('grid grid-cols-2 gap-3')}`,
  `              ${open('space-y-1')}`,
  `                <Label htmlFor="first">Ime (opciono)</Label>`,
  `                <Input id="first" value={firstName} onChange={(e) => setFirstName(e.target.value)} />`,
  `              ${close}`,
  `              ${open('space-y-1')}`,
  `                <Label htmlFor="last">Prezime (opciono)</Label>`,
  `                <Input id="last" value={lastName} onChange={(e) => setLastName(e.target.value)} />`,
  `              ${close}`,
  `            ${close}`,
  `            ${open('space-y-1')}`,
  `              <Label htmlFor="pw">Lozinka</Label>`,
  `              <Input id="pw" type="password" value={password} onChange={(e) => setPassword(e.target.value)} required minLength={6} />`,
  `            ${close}`,
  `            ${open('space-y-1')}`,
  `              <Label htmlFor="pw2">Ponovi lozinku</Label>`,
  `              <Input id="pw2" type="password" value={password2} onChange={(e) => setPassword2(e.target.value)} required />`,
  `            ${close}`,
  `            {error && <p className="text-sm text-red-600">{error}</p>}`,
  `            <Button type="submit" className="w-full" disabled={submitting}>`,
  `              {submitting && <Loader2 className="w-4 h-4 mr-2 animate-spin" />}`,
  `              Kreiraj nalog`,
  `            </Button>`,
  `          </form>`,
  `        )}`,
  `      ${close}`,
  `    ${close}`,
  `  );`,
  `}`,
  ``,
];

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/pages/AcceptInvite.jsx');
fs.writeFileSync(out, lines.join('\n'));
console.log('Wrote', out);
